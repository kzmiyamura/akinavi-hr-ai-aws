-- relevance_keywords 品質修正
-- 広すぎるキーワードを削除する。
-- 理由: 汎用語はビジネスメール・技術ニュース・求人サイト通知にも出現し
--       無関係なメールを relevant:true にしてしまうため。
-- 複合形（業務委託案件・案件のご紹介・ITエンジニア 等）は残す。

DELETE FROM relevance_keywords WHERE keyword IN (
  -- candidate: 単体では広すぎる
  'エンジニア',       -- → ITエンジニア/システムエンジニア/各種複合形で代替
  '技術者',           -- 技術系ニュース・一般記事にも出現
  'フリーランス',     -- → フリーランスエンジニアで代替
  -- project: 2文字 or 汎用すぎる
  '案件',             -- 法律・営業・一般ビジネスに多用
  '現場',             -- 「現場の声」「現場監督」など超多義語
  '派遣',             -- 一般HR文書に広く出現
  '予算',             -- あらゆるビジネスメールに出現
  '要員',             -- 一般ビジネス
  '急募',             -- 一般求人サイト通知
  '請負',             -- 一般契約文書
  '業務委託',         -- → 業務委託案件で代替
  '業務内容',         -- 一般求人票・社内文書に頻出
  '担当業務',         -- 一般HR・社内文書
  '作業内容',         -- 一般業務文書
  '就業場所',         -- 一般求人
  '勤務地',           -- 一般求人サイト全般
  '稼働時間',         -- 一般労務文書
  '契約期間',         -- 一般契約文書
  '開始時期',         -- 一般ビジネス文書
  '開発案件'          -- 「案件」より絞れているが IT ニュースにも出現
);
