--   希望単価で分かれるので足す。
--   デザイナーは45人・単価70万で全体と同じだったため**足さない**
--   （分かれない役割に印を付けない。意味のない印は害になる）。
--
-- 軸の置き方（docs/ROLE_DEFINITION.md）:
--   ディレクター … object=成果（制作物）/ authority=3（統率）
--     要件定義からワイヤーフレーム、制作メンバーへの指示出しと進行管理まで担う。
--     プロジェクトリーダーと同じ座標になるが、この2軸は領域を表さない設計
--     （エンジニア職も全員 製品×2 で重なる）。制作かシステムかはスキル一致側で分かれる。
--   マーケター   … object=事業（売上・集客）/ authority=2（実行）
--     広告運用や分析を自分で回す。同じ事業でもコンサルタント(3)とは権限が違う。
--
-- ⚠ 役割を触る場所は4つ。すべて同時に直すこと（ズレ検出は
--    src/lib/__tests__/roleAffinityParity.test.ts と scripts/sql/test_role_affinity.sql）:
--      このSQL / match-batch の ROLE_AXIS / inbound-email の ROLE_DEFS /
