// ── 走査 ────────────────────────────────────────────────────────────────────
const stat = CANDIDATES.map(([label, re]) => ({
  label, re: new RegExp(re.source, re.flags.includes('i') ? 'i' : ''),
  mails: 0, noRole: 0, existing: new Map(),
}))
let mails = 0

for (const day of readdirSync(ROOT, { withFileTypes: true })) {
  if (!day.isDirectory()) continue
  for (const m of readdirSync(join(ROOT, day.name), { withFileTypes: true })) {
    if (!m.isDirectory()) continue
    const p = join(ROOT, day.name, m.name, 'message.json')
    if (!existsSync(p)) continue
    let j
    try { j = JSON.parse(readFileSync(p, 'utf8').replace(/^\uFEFF/, '')) } catch { continue }
    const text = (j.subject ?? '') + '\n' + (j.body ?? '')
    mails++
    let roles = null           // 必要になるまで抽出しない（遅いので）
    for (const s of stat) {
      if (!s.re.test(text)) continue
      s.mails++
      if (roles === null) roles = extractFromProse(text, '').roles
      if (roles.length === 0) s.noRole++
      for (const r of roles.slice(0, 3)) s.existing.set(r, (s.existing.get(r) ?? 0) + 1)
    }
  }
}

// ── 出力 ────────────────────────────────────────────────────────────────────
