console.log('  * = すでに役割ラベルがあるもの')
console.log('  実在 = その語が出てくるメール数 / 無印 = うち役割が1つも付かないメール数\n')
const rows = stat.filter(s => s.mails >= MIN).sort((a, b) => b.mails - a.mails)
console.log('  実在   無印   %    職種                              いま付いている役割(上位3)')
console.log('  ' + '─'.repeat(100))
for (const s of rows) {
  const top = [...s.existing.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3)
    .map(([k, v]) => `${k}:${v}`).join(' ')
  const pct = s.mails ? ((s.mails / mails) * 100).toFixed(1) : '0.0'
  console.log(`  ${String(s.mails).padStart(5)} ${String(s.noRole).padStart(5)} ${pct.padStart(5)}  ${s.label.padEnd(32)} ${top}`)
}
const absent = stat.filter(s => s.mails < MIN)
if (absent.length) {
  console.log(`\n  うちのデータに出てこない（${absent.length}種）:`)
  console.log('    ' + absent.map(s => s.label).join('、'))
}
