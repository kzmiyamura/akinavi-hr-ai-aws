-- AI校正の日次上限を 150 → 300 に上げる（2026-09-22）
--
-- ⚠ 制限値には「何を守るか」と「測った数字」を残すこと（sender_daily_limit の教訓）。
--
-- 何を守っている上限なのか:
--   LLM の費用ではない。ワーカーは `claude -p`（Max枠）で動いており実課金は発生しない。
--   実際に効いている制約は **Supabase Storage の egress**。
--   ワーカーは経歴書を毎回 Storage からダウンロードしており、
--   実体は平均約315KB（CLAUDE.md の実測値・最大1.8MB）。Free プランは月5GB。
--
-- 測った数字（2026-09-22）:
--   登録のうち経歴書ありは 176/252 = 70%
--   150件/日 × 70% × 315KB ≒ 31MB/日 ≒ 0.95GB/月
--
--   同日、添付解析の再利用を入れた（llm_shadow.source_url）。
--   ログ実測で添付解析の 41.6% が同じファイルの再解析だったため、
--   再利用ぶんはダウンロードごと省かれる:
--     150件/日 → 実ダウンロード ≒ 58件/日 ≒ 18MB/日
--
--   したがって 300件/日 にしても実ダウンロードは ≒ 117件/日 ≒ 37MB/日 で、
--   **変更前（31MB/日）とほぼ同じ egress** に収まる。
--
-- なぜ上げるのか:
--   9/18 は登録1,357件に対し校正289件(21%)。経歴書を持ったまま未校正が639人。
--   3日を過ぎて二度と拾われない人が1,498人（うち経歴書あり668人）。
--   経歴書が読まれない人は regex 抽出だけの状態で、案件履歴もスキル年数も空のまま
--   営業の前に出る。
--
-- 次に見るもの:
--   ・Storage egress の実測（想定どおり横ばいか）
--   ・ワーカーが実際に300件こなせるか（添付解析は1件1〜3分。時間の方が先に尽きる可能性）
--   どちらかが外れたら下げる。

update app_config set value = '300'::jsonb where key = 'shadow_max_per_day';

select key, value from app_config where key = 'shadow_max_per_day';
