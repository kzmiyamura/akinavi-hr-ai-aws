SELECT
  CASE WHEN role_affinity(required, candidate, lv) = expected THEN 'ok' ELSE 'NG' END AS result,
  COALESCE(required, '(null)')  AS 案件が求める,
  COALESCE(candidate, '(null)') AS 人材の主役割,
  COALESCE(lv, '(未判定)')      AS 到達,
  expected                      AS 期待,
  role_affinity(required, candidate, lv) AS 実際,
  memo
FROM cases
UNION ALL
-- 2引数版がレベル不明として委譲されること
SELECT
  CASE WHEN role_affinity('プロジェクトマネージャー', 'PMO')
          = role_affinity('プロジェクトマネージャー', 'PMO', NULL) THEN 'ok' ELSE 'NG' END,
