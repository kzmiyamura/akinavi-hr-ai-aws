-- role_affinity の単体テスト。期待値と食い違ったら NG 行が出る。
-- 定義と根拠は docs/ROLE_DEFINITION.md。式は 20260901_role_taxonomy.sql。
--
-- 原則: **役割は「責任の形」だけを表す。技術領域の違いはスキル一致が受け持つ。**
--   役割でも領域でも減点すると二重に減点になる（ヘルプデスク案件のMLエンジニアは
--   スキル一致がゼロなので役割で追い討ちしなくてよい）。
WITH cases(required, candidate, expected, memo) AS (VALUES
  -- ── 完全一致 ──
  ('PMO',                      'PMO',                      1.0,    '同一ラベル'),
  ('ヘルプデスク',             'ヘルプデスク',             1.0,    '同一ラベル'),

  -- ★ 今回の主目的: PM と PMO は雲泥の差（対象も権限も最遠）。旧は 0.7 だった
  ('プロジェクトマネージャー', 'PMO',                      0.2,    '★PM案件にPMO＝最遠。旧0.7'),
  ('PMO',                      'プロジェクトマネージャー', 0.2,    '★逆向きも同じ'),

  -- ── 対象が同じ・権限が近い ──
  ('プロジェクトマネージャー', 'プロジェクトリーダー',     0.75,   'PM案件にPL＝対象同じ・権限1段差'),
  ('システムエンジニア',       'プログラマー',             0.9,    '同じマス（上限0.9）'),
  ('ヘルプデスク',             '運用保守',                 0.75,   '対象サービス同士・権限1段差'),
  ('システムエンジニア',       'アーキテクト',             0.75,   '対象製品同士・権限1段差。旧0.2は誤り'),
  ('PMO',                      'スクラムマスター',         0.75,   '対象「仕組み」同士'),

  -- ── 対象が隣接 ──
  ('ヘルプデスク',             'PMO',                      0.6,    '権限同じL1・対象隣接。「運用サポートはPMOも含む」を維持'),
  ('プロジェクトリーダー',     'テックリード',             0.6,    '統率同士。旧0.2は誤り'),
  ('コンサルタント',           'アーキテクト',             0.6,    '事業↔製品の隣接・権限同じ'),
  ('運用保守',                 'PMO',                      0.45,   '対象隣接・権限1段差'),
  ('プロジェクトリーダー',     'システムエンジニア',       0.45,   '旧0.2は誤り（PLと実装は近い）'),
  ('プロジェクトマネージャー', 'システムエンジニア',       0.30,   '対象隣接・権限2段差'),
  ('プログラマー',             'プロジェクトマネージャー', 0.30,   '逆向き'),

  -- ── 対象が遠い ──
  ('システムエンジニア',       'PMO',                      0.2625, '★実装案件のPMO＝2026-08-14の不具合。低いまま維持'),
  ('プロジェクトマネージャー', 'ヘルプデスク',             0.2,    '対象も権限も最遠'),

  -- ── 技術領域の違いは役割では減点しない（スキル一致が受け持つ）──
  ('ヘルプデスク',             'MLエンジニア',             0.45,   '役割の形は近い。畑違いはスキル側で落ちる'),

  -- ── 不明は中立 ──
  ('システムエンジニア',       NULL,                       0.5,    '人材側に役割なし'),
  (NULL,                       'PMO',                      0.5,    '案件側に要求役割なし'),
  ('',                         'PMO',                      0.5,    '空文字も不明扱い'),
  ('システムエンジニア',       'データサイエンティスト',   0.5,    '一覧に無いラベルは中立（旧は0.2に落としていた）')
)
SELECT
  CASE WHEN role_affinity(required, candidate) = expected THEN 'ok' ELSE 'NG' END AS result,
  COALESCE(required, '(null)')  AS 案件が求める,
  COALESCE(candidate, '(null)') AS 人材の主役割,
  expected                      AS 期待,
  role_affinity(required, candidate) AS 実際,
  memo
FROM cases
ORDER BY result DESC, memo;
