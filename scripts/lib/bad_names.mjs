/**
 * 氏名として成立しているかの判定規則（純粋関数・副作用なし）。
 *
 * 一覧に「オープン系」「昭和３３年５月１３日」「氏名」が人の名前として並ぶと、
 * **それだけで製品の信頼を失う**（2026-08-10 ユーザー指摘）。
 *
 * ## なぜ独立したファイルなのか
 *
 * 元は `scripts/audit_bad_names.mjs` の中にあったが、あのファイルは
 * **モジュール先頭で `~/.akinavi_shadow.env` を読み、prod を全件ページングする**。
 * そこから import すると、egress ゼロを謳う夜間健診が
 * 「秘密ファイルが無いと落ちる検出器」になってしまう（実際に import していた）。
 *
 * 規則をここに置き、**prod を引く監査（audit_bad_names.mjs）と
 * 控えで回る検出器（selfcheck/detectors/bad_names.mjs）の両方が同じ関数を使う**。
 * 書き写すと必ずズレる（手書きレプリカの test_extraction.mjs で実績がある）。
 */

/**
 * 「文字」と見なす字種。
 *
 * ⚠ **半角カナ（ｦ-ﾝ = ｦ〜ﾝ）を必ず含める。**
 *    含めないと `呂V（ﾛ）` のような半角カナ読み付きの実名が「文字なし」になる。
 *    控えの実測（2026-10-03・prod 8,215人）では半角カナを含む氏名は2人で、
 *    **うち1人は実名**だった。濁点・半濁点（ﾞ-ﾟ）は単独では文字でないので入れない。
 */
const LETTER_RE = /[A-Za-zＡ-Ｚａ-ｚぁ-んァ-ヶ一-龥ｦ-ﾝ]/

/**
 * 表の見出しがそのまま氏名として登録されたもの。
 *
 * 控えの実測（2026-10-03）で `フリガナ` / `氏名` / `ｶﾅ` が **5人**いた。
 * Excel の氏名欄の見出し行を1人目として読んでいる＝抽出の取り違えで、
 * AI校正でも埋まらない（元の本文にも名前が無い）。
 *
 * ⚠ **全角の「カナ」「かな」は入れない。** 実在する下の名前なので、
 *    本物の人を見出し語と呼ぶ危険がある。半角の `ｶﾅ` / `ﾌﾘｶﾞﾅ` は
 *    人が自分の名前をそう書くことがないので安全に入れられる。
 */
const HEADER_LABEL_RE =
  /^(不明|未定|なし|該当なし|要員|人材|エンジニア|技術者|氏名|名前|お名前|氏名カナ|氏名（カナ）|フリガナ|ふりがな|ﾌﾘｶﾞﾅ|ｶﾅ)$/

/**
 * 氏名として成立しない理由を返す（空配列なら問題なし）。
 * 1つの名前が複数の理由に当たることがある（「昭和３３年」＝全角数字＋元号）。
 */
export function badNameReasons(name) {
  const s = String(name ?? '').trim()
  const r = []
  if (!s) return ['空']
  // 全角数字を含む（生年月日・年齢の巻き込み）。JSの \d は全角にマッチしないため個別に見る
  if (/[０-９]/.test(s)) r.push('全角数字')
  if (/\d/.test(s)) r.push('半角数字')
  // 元号つきの日付
  if (/(昭和|平成|令和|大正)/.test(s)) r.push('元号(生年月日)')
  // スキル分類・工程・属性のラベル
  if (/(オープン系|汎用系|制御系|組込|インフラ|ネットワーク|サーバ|アプリ|開発系|運用系)$/.test(s)) r.push('スキル分類')
  if (HEADER_LABEL_RE.test(s)) r.push('プレースホルダ')
  // 記号のみ・極端に長い
  if (!LETTER_RE.test(s)) r.push('文字なし')
  if (s.length > 20) r.push(`長すぎる(${s.length}字)`)
  return r
}
